import assert from 'node:assert/strict';
import {GardenLife,GARDEN_ITEMS} from '../garden-life.mjs';
const view={active:true,answering:true,remainingChords:2,width:390,height:844,x:195,y:472};
const life=new GardenLife({random:()=>.2});
assert(GARDEN_ITEMS.restoration.rare&&!GARDEN_ITEMS.restoration.artifact);
life.resources={fuel:0,water:9,crew:17,hull:1};life.critical={resource:'fuel',age:3.4};
const wheel=life.forceSpawn('restoration');
assert(life.collect(wheel));assert.deepEqual(life.resources,{fuel:100,water:100,crew:100,hull:100});assert.equal(life.critical,null);
assert(!life.collect(wheel),'one pickup cannot be spent twice');assert(!('restoration' in life.inventory),'restoration is immediate, not another inventory control');
life.reset();life.time=20;life.setResource('water',12);
assert.equal(life.maybeSpawnRestoration(.05,{...view,active:false}),null);
assert.equal(life.maybeSpawnRestoration(.05,{...view,remainingChords:4}),null);
const rescue=life.maybeSpawnRestoration(.05,view);assert(rescue);assert(rescue.y>.1&&rescue.y<view.y/view.height,'critical rescue enters visibly ahead of ship');
assert.equal(life.maybeSpawnRestoration(.05,view),null,'at most one wheel per flight');
const unlucky=new GardenLife({random:()=>.9});unlucky.time=20;unlucky.setResource('hull',10);
assert.equal(unlucky.maybeSpawnRestoration(.05,view),null);assert(unlucky.restorationRescueChecked);
unlucky.random=()=>0;assert.equal(unlucky.maybeSpawnRestoration(.05,view),null,'rescue lottery is not retried every frame');
life.reset();life.time=61;life.random=()=>0;assert(life.maybeSpawnRestoration(.05,{...view,remainingChords:8}),'rare background chance exists away from final chords');
life.reset();life.gameOver=true;assert(!life.collect(life.forceSpawn('restoration')),'cannot revive a finished fatal collision');
life.reset();assert(!life.restorationAppeared&&!life.restorationRescueChecked);
console.log('Restoration PASS: immediate exact 100% all reserves, clears critical countdown, no double pickup/inventory, one rescue lottery, rare background chance, no post-game resurrection, reset.');
