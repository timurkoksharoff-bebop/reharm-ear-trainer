import assert from 'node:assert/strict';
import {createGardenRewards} from '../garden-rewards.mjs';
import {createGardenMission} from '../garden-harmony.mjs';
const effects=createGardenRewards({rng:()=>.5});
const mission=createGardenMission({exercise:{baseTonic:5,sequence:[{offset:0,quality:'6'},{offset:5,quality:'maj'}]},onChord(){}});
mission.start();mission.advance();
assert(!effects.answer(mission.answerPart('degree',1),'degree'));assert.equal(effects.snapshot().count,0);
assert(effects.answer(mission.answerPart('degree',0),'degree'));assert.equal(effects.snapshot().motes,9);assert.equal(effects.snapshot().vines,1);
assert(!effects.answer(mission.answerPart('degree',0),'degree'));assert.equal(effects.snapshot().count,1);
assert(effects.answer(mission.answerPart('quality','6'),'quality'));assert.equal(effects.snapshot().blooms,1);assert.equal(effects.snapshot().waves,1);
effects.step(.5);let arcs=0;const gradient={addColorStop(){}};
effects.draw({save(){},restore(){},createRadialGradient(){return gradient;},beginPath(){},moveTo(){},lineTo(){},arc(){arcs++;},ellipse(){},fill(){},stroke(){},translate(){},rotate(){}},390,844);assert(arcs>10);
for(let i=0;i<100;i++)effects.answer({correct:true,positionComplete:true},'degree');
assert(effects.snapshot().motes<=88&&effects.snapshot().waves<=4);
effects.step(6);assert.equal(effects.snapshot().motes,0);assert.equal(effects.snapshot().blooms,0);assert.equal(effects.snapshot().waves,0);
effects.reset();assert.equal(effects.snapshot().count,0);
const still=createGardenRewards({reduced:true});still.answer({correct:true},'degree');assert.equal(still.snapshot().motes,3);
console.log('Garden nature rewards: correct-only independent parts, no duplicate reward, bounded effects, expiry/reset and reduced motion passed.');
mission.pause();
